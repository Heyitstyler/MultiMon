static BOOL Verify(const char *msg, const unsigned char *sig, const unsigned char *mod) {
    sArenaUsed = 0;
    return (u32)CRYPTO_VerifySignature((u32)(uintptr_t)msg, (u32)strlen(msg), (u32)(uintptr_t)sig, (u32)(uintptr_t)mod) != 0;
}

int pc_crypto_selftest(void) {
    /* RC4: key "Key", "Plaintext" -> bb f3 16 e8 d9 40 af 0a d3. Context: i, j, 2 pad bytes, S[256]. */
    static unsigned char ctx[4 + 256];
    static const unsigned char want[9] = { 0xbb, 0xf3, 0x16, 0xe8, 0xd9, 0x40, 0xaf, 0x0a, 0xd3 };
    unsigned char out[9];
    CRYPTO_RC4Init((u32)(uintptr_t)ctx, (u32)(uintptr_t)"Key", 3u);
    CRYPTO_RC4Encrypt((u32)(uintptr_t)ctx, (u32)(uintptr_t)"Plaintext", 9u, (u32)(uintptr_t)out);
    int ok = memcmp(out, want, 9) == 0;

    CRYPTO_SetAllocator((u32)(uintptr_t)ArenaAlloc, (u32)(uintptr_t)ArenaFree);
    ok &= Verify(sMsg0, sSig0, sMod0) && Verify(sMsg1, sSig1, sMod1) && Verify(sMsg2, sSig2, sMod2);
    unsigned char bad[128];
    memcpy(bad, sSig1, sizeof bad);
    bad[77] ^= 0x10;
    ok &= !Verify(sMsg1, bad, sMod1);          /* corrupted signature */
    ok &= !Verify(sMsg0, sSig1, sMod1);         /* signature for another message */
    ok &= !Verify(sMsg2, sSig2, sMod0);         /* wrong key */
    return ok;
}
